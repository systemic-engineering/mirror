"""Constant-sheaf kintsugi over the `in @X` cover (Mara 2026-10-29).

Sigma: vertices = declarations (owned by exactly one shard), edges = references
d -> r (owned by the shard declaring d). K_i = closed subcomplex generated by
shard i's declarations and its reference edges (so it contains the referents).
Every edge is private by construction; overlaps are edgeless.

Three independent counts of the comma among all, ker(H^1(Sigma) -> (+)H^1(K_i)):
  A  Euler / union-find:   b1(Sigma) - sum_i b1(K_i)
  B  Cech nerve:           dim H^1 of  (+)H^0(K_i) -> (+)H^0(K_ij) -> (+)H^0(K_ijk)
  C  linear algebra:       b1(Sigma) - rank( (+)Z(K_i) -> Z(Sigma) )
Also: Cech H^2(N; H^0) (expected 0), T29 private edits, fixtures.
"""
import itertools, random
import numpy as np

def uf_components(vertices, edges):
    parent = {v: v for v in vertices}
    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for (a, b) in edges:
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[ra] = rb
    comp = {v: find(v) for v in vertices}
    return comp, len(set(comp.values()))

def b1(vertices, edges):
    _, b0 = uf_components(vertices, edges)
    return len(edges) - len(vertices) + b0

def build(owner, refs, n):
    """owner: decl -> shard; refs: list of (d, r) with d != r."""
    V = sorted(owner)
    E = [(d, r) for (d, r) in refs]
    K = []
    for i in range(n):
        Ei = [(d, r) for (d, r) in E if owner[d] == i]
        Vi = set(d for d in V if owner[d] == i) | set(r for (_, r) in Ei)
        K.append((sorted(Vi), Ei))
    return V, E, K

def oracle_A(V, E, K):
    return b1(V, E) - sum(b1(Vi, Ei) for (Vi, Ei) in K)

def Ksigma(K, sigma):
    vs = set(K[sigma[0]][0])
    es = set(K[sigma[0]][1])
    for i in sigma[1:]:
        vs &= set(K[i][0]); es &= set(K[i][1])
    return sorted(vs), sorted(es)

def cech(K, n, top=3):
    """Cech complex of H^0 over the nerve, degrees 0..top. Returns dims of H^0..H^{top-1}."""
    simplices = {p: [] for p in range(top + 1)}
    comps = {}
    for p in range(top + 1):
        for sigma in itertools.combinations(range(n), p + 1):
            vs, es = Ksigma(K, sigma)
            if vs:
                comp, _ = uf_components(vs, es)
                reps = sorted(set(comp.values()))
                simplices[p].append(sigma)
                comps[sigma] = (comp, reps)
    def index(p):
        idx, off = {}, 0
        for s in simplices[p]:
            for r in comps[s][1]:
                idx[(s, r)] = off; off += 1
        return idx, off
    idxs = [index(p) for p in range(top + 1)]
    mats = []
    for p in range(top):
        src, ns = idxs[p]; dst, nd = idxs[p + 1]
        D = np.zeros((nd, ns))
        for tau in simplices[p + 1]:
            comp_t, reps_t = comps[tau]
            for k in range(len(tau)):
                sigma = tau[:k] + tau[k + 1:]
                comp_s, _ = comps[sigma]
                sign = (-1) ** k
                for r in reps_t:
                    D[dst[(tau, r)], src[(sigma, comp_s[r])]] += sign
        mats.append(D)
    rank = lambda M: 0 if M.size == 0 else np.linalg.matrix_rank(M)
    dims = [idxs[p][1] for p in range(top + 1)]
    H = []
    for p in range(top):
        rk_out = rank(mats[p])
        rk_in = rank(mats[p - 1]) if p > 0 else 0
        H.append(dims[p] - rk_out - rk_in)
    return H

def cycle_basis_matrix(vertices, edges, all_edges_index):
    """Rows of a basis of the cycle space Z of (vertices, edges) as vectors over all edges."""
    vi = {v: k for k, v in enumerate(vertices)}
    B = np.zeros((len(vertices), len(edges)))
    for k, (a, b) in enumerate(edges):
        if a == b:
            continue
        B[vi[a], k] -= 1; B[vi[b], k] += 1
    # null space of B
    if len(edges) == 0:
        return np.zeros((0, len(all_edges_index)))
    u, s, vt = np.linalg.svd(B)
    r = int((s > 1e-9).sum())
    Z = vt[r:]
    out = np.zeros((Z.shape[0], len(all_edges_index)))
    for k, e in enumerate(edges):
        out[:, all_edges_index[e]] = Z[:, k]
    return out

def oracle_C(V, E, K):
    eidx = {e: k for k, e in enumerate(E)}
    blocks = [cycle_basis_matrix(Vi, Ei, eidx) for (Vi, Ei) in K]
    M = np.vstack(blocks) if blocks else np.zeros((0, len(E)))
    rk = 0 if M.shape[0] == 0 else np.linalg.matrix_rank(M)
    return b1(V, E) - rk, M.shape[0]  # second: sum of local b1 (= rank iff direct sum)

def random_cover(rng, n, decls_per, refs_per, p_foreign):
    owner = {}
    for i in range(n):
        for k in range(rng.randint(1, decls_per)):
            owner[f"s{i}.d{k}"] = i
    D = sorted(owner)
    refs = set()
    for d in D:
        for _ in range(rng.randint(0, refs_per)):
            if rng.random() < p_foreign:
                r = rng.choice(D)
            else:
                r = rng.choice([x for x in D if owner[x] == owner[d]])
            if r != d:
                refs.add((d, r))
    return owner, sorted(refs)

def check_random(trials=1500, seed=20261029):
    rng = random.Random(seed)
    agree_AB = agree_AC = h2_zero = direct = 0
    nontriv = 0
    for _ in range(trials):
        n = rng.randint(2, 5)
        owner, refs = random_cover(rng, n, 4, 3, 0.4)
        V, E, K = build(owner, refs, n)
        a = oracle_A(V, E, K)
        h = cech(K, n, top=3)
        c, sumloc = oracle_C(V, E, K)
        agree_AB += (a == h[1]); agree_AC += (a == c)
        h2_zero += (h[2] == 0)
        direct += (sumloc == sum(b1(Vi, Ei) for Vi, Ei in K))
        nontriv += (a > 0)
    print(f"RANDOM {trials}: A==B {agree_AB}, A==C {agree_AC}, H2(N;H0)==0 {h2_zero}, "
          f"local cycle spaces direct {direct}, comma>0 in {nontriv}")

def check_T29(trials=1500, seed=29):
    rng = random.Random(seed)
    same = same_ok = join = join_ok = 0
    for _ in range(trials):
        n = rng.randint(2, 5)
        owner, refs = random_cover(rng, n, 4, 3, 0.4)
        V, E, K = build(owner, refs, n)
        _, b0S = uf_components(V, E)
        if b0S != 1:
            continue
        i = rng.randrange(n)
        Vi, Ei = K[i]
        decls_i = [d for d in Vi if owner[d] == i]
        comp, _ = uf_components(Vi, Ei)
        d = rng.choice(decls_i)
        cands = [v for v in Vi if v != d and (d, v) not in set(refs)]
        if not cands:
            continue
        r = rng.choice(cands)  # already in K_i: a private-cell edit
        before = oracle_A(V, E, K)
        V2, E2, K2 = build(owner, refs + [(d, r)], n)
        after = oracle_A(V2, E2, K2)
        if comp[d] == comp[r]:
            same += 1; same_ok += (after == before)
        else:
            join += 1; join_ok += (after == before + 1)
    print(f"T29: inside a component {same_ok}/{same} unchanged; joining two components {join_ok}/{join} +1")

def fixture(name, owner, refs, n):
    V, E, K = build(owner, refs, n)
    a = oracle_A(V, E, K); h = cech(K, n, 3); c, _ = oracle_C(V, E, K)
    pair = []
    for (i, j) in itertools.combinations(range(n), 2):
        sub = [x for x in owner if owner[x] in (i, j)]
        o2 = {x: (0 if owner[x] == i else 1) for x in sub}
        r2 = [(d, r) for (d, r) in refs if owner[d] in (i, j)]
        # restrict Sigma to K_i u K_j (referents kept as vertices owned by whoever)
        Vu = sorted(set(K[i][0]) | set(K[j][0])); Eu = K[i][1] + K[j][1]
        pair.append(b1(Vu, Eu) - b1(*K[i]) - b1(*K[j]))
    print(f"{name}: A={a} B={h[1]} C={c} H2={h[2]} pairwise={pair} b1(Sigma)={b1(V, E)}")

